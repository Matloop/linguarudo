/** Códigos que o BCP 47 escreve diferente do Whisper. */
const ALIASES: Record<string, string> = {
	nb: 'no', // bokmål
	iw: 'he', // hebraico, código antigo
	in: 'id', // indonésio, código antigo
	ji: 'yi',
	jv: 'jw', // o Whisper usa "jw" para javanês
	fil: 'tl',
	cmn: 'zh',
	yue: 'zh', // cantonês: os modelos tiny/base não têm "yue"; chinês é o mais próximo
	zsm: 'ms'
};

export function whisperLanguage(bcp47: string | null | undefined): string | undefined {
	if (!bcp47) return undefined;
	const primary = bcp47.trim().toLowerCase().split(/[-_]/)[0];
	if (!primary) return undefined;
	const code = Object.hasOwn(ALIASES, primary) ? ALIASES[primary] : primary;
	return Object.hasOwn(WHISPER, code) ? WHISPER[code] : undefined;
}
